@dataclass(frozen=True)
class PromptTemplate:
    name: str
    version: str
    system: str
    user: str

    @property
    def hash(self) -> str:
        return sha256_hex("\x1f".join((self.name, self.version, self.system, self.user)))[:16]

    @property
    def label(self) -> str:
        return f"{self.name}@{self.version}#{self.hash[:8]}"

    def render(self, **values: str) -> tuple[str, str]:
        return self.system, Template(self.user).substitute(**values)


