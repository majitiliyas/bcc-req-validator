from .cache import sha256_hex

UNTRUSTED_OPEN = "<untrusted_document>"
UNTRUSTED_CLOSE = "</untrusted_document>"


_FENCE_TAGS = ("untrusted_document", "full_document_context")


def _neutralize(text: str) -> str:
    for tag in _FENCE_TAGS:
        text = text.replace(f"<{tag}", f"‹{tag}").replace(f"</{tag}", f"‹/{tag}")
    return text


def spotlight(text: str) -> str:
    """Обернуть недоверенный текст; попытки «закрыть» тег изнутри документа обезвреживаются."""
    return f"{UNTRUSTED_OPEN}\n{_neutralize(text)}\n{UNTRUSTED_CLOSE}"


def full_context_block(text: str | None) -> str:
    """Полный текст документа как справочный контекст (тоже недоверенные данные)."""
    if not text:
        return "— (документ больше порога полного контекста; используй Глобальный реестр)"
    return f"<full_document_context>\n{_neutralize(text)}\n</full_document_context>"


