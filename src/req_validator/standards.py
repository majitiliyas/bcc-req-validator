def norm_text(rule_id: str) -> str:
    """Норма для промпта/критика: определение + ссылка + что не считать дефектом."""
    c = criterion_of(rule_id)
    if c is None:
        return rule_id
    fp = FALSE_POSITIVES.get(c.rule_id, "")
    return f"{c.rule_id} «{c.name_ru}» ({c.name_en}; {c.reference}): {c.definition} НЕ дефект: {fp}"


def catalog_text(criteria: tuple[Criterion, ...]) -> str:
    return "\n".join(f"- {norm_text(c.rule_id)}" for c in criteria)
